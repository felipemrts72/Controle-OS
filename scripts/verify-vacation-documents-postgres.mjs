import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import pg from 'pg';
import jwt from 'jsonwebtoken';

const storage = await fs.mkdtemp(path.join(os.tmpdir(),'olimen-docs-qa-'));
process.env.VACATION_DOCUMENT_DIR = storage;
const { uploadVacationDocument, listVacationDocuments, readVacationDocument, archiveVacationDocument, zipVacationPeriod } = await import('../backend/src/services/vacationDocumentService.js');
const client = new pg.Client({ connectionString:process.env.DATABASE_URL });
await client.connect();
const pdf=Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF');
const png=Buffer.from('89504e470d0a1a0a0000000049454e44ae426082','hex');
try {
  const actor=(await client.query("SELECT id FROM users WHERE username='felipe'")).rows[0].id;
  const employee=(await client.query("INSERT INTO employees(full_name,admission_date,employment_status,current_salary) VALUES('QA Documentos de Férias','2024-01-01','ativo',2500) RETURNING id")).rows[0].id;
  const other=(await client.query("INSERT INTO employees(full_name,admission_date,employment_status,current_salary) VALUES('QA Outro Funcionário','2024-01-01','ativo',2500) RETURNING id")).rows[0].id;
  const period=(await client.query("INSERT INTO vacation_periods(employee_id,ordinal,acquisition_start,acquisition_end,concession_start,concession_end) VALUES($1,1,'2024-01-01','2024-12-31','2025-01-01','2025-12-31') RETURNING id",[employee])).rows[0].id;
  const leave=(await client.query("INSERT INTO vacation_leaves(employee_id,period_id,start_date,end_date,days,status,created_by) VALUES($1,$2,'2025-06-01','2025-06-15',15,'historica',$3) RETURNING id",[employee,period,actor])).rows[0].id;
  const before=(await client.query('SELECT days,status FROM vacation_leaves WHERE id=$1',[leave])).rows[0];
  const receipt=await uploadVacationDocument(employee,period,leave,{documentType:'signed_receipt',originalName:'recibo.pdf',mime:'application/pdf'},pdf,actor);
  const photo=await uploadVacationDocument(employee,period,leave,{documentType:'other',originalName:'foto.png',mime:'image/png',description:'Arquivo sintético'},png,actor);
  assert.equal((await listVacationDocuments(employee,period,leave)).length,2);
  assert.deepEqual((await readVacationDocument(employee,period,leave,receipt.id,actor)).buffer,pdf);
  assert.deepEqual((await readVacationDocument(employee,period,leave,photo.id,actor)).buffer,png);
  await assert.rejects(() => readVacationDocument(other,period,leave,receipt.id,actor));
  await assert.rejects(() => listVacationDocuments(employee,other,leave));
  await assert.rejects(() => listVacationDocuments(employee,period,other));
  const zip=await zipVacationPeriod(employee,period,actor);
  assert.ok(zip.includes(pdf) && zip.includes(png));
  await archiveVacationDocument(employee,period,leave,receipt.id,actor);
  assert.equal((await listVacationDocuments(employee,period,leave)).length,1);
  assert.deepEqual((await client.query('SELECT days,status FROM vacation_leaves WHERE id=$1',[leave])).rows[0],before);
  const events=(await client.query("SELECT action FROM vacation_audit WHERE employee_id=$1 AND entity_type='document'",[employee])).rows.map((row)=>row.action);
  assert.ok(events.includes('document_upload') && events.includes('document_download') && events.includes('document_archive'));
  const { app } = await import('../backend/src/app.js');
  const server=await new Promise((resolve) => { const instance=app.listen(0,'127.0.0.1',()=>resolve(instance)); });
  try {
    const port=server.address().port;
    const viewer=(await client.query("SELECT id FROM users WHERE username='qa_viewer'")).rows[0].id;
    const auth=(id)=>({ Authorization:`Bearer ${jwt.sign({id},process.env.JWT_SECRET || 'dev-secret')}` });
    const endpoint=`http://127.0.0.1:${port}/api/vacations/employees/${employee}/periods/${period}/leaves/${leave}/documents`;
    const deniedUpload=await fetch(endpoint,{method:'POST',headers:{...auth(viewer),'Content-Type':'application/pdf','x-document-type':'signed_receipt','x-original-name':'qa.pdf'},body:pdf});
    assert.equal(deniedUpload.status,403);
    const deniedDownload=await fetch(`${endpoint}/${photo.id}`,{headers:auth(viewer)});
    assert.equal(deniedDownload.status,403);
    const otherEmployee=await fetch(`http://127.0.0.1:${port}/api/vacations/employees/${other}/periods/${period}/leaves/${leave}/documents/${photo.id}`,{headers:auth(actor)});
    assert.equal(otherEmployee.status,404);
    const download=await fetch(`${endpoint}/${photo.id}?download=1`,{headers:auth(actor)});
    assert.equal(download.status,200);
    assert.deepEqual(Buffer.from(await download.arrayBuffer()),png);
    const zipped=await fetch(`http://127.0.0.1:${port}/api/vacations/employees/${employee}/periods/${period}/documents.zip`,{headers:auth(actor)});
    assert.equal(zipped.status,200);
    assert.ok(Buffer.from(await zipped.arrayBuffer()).includes(png));
  } finally { await new Promise((resolve)=>server.close(resolve)); }
  const stored=(await client.query('SELECT stored_name FROM vacation_documents WHERE id=$1',[photo.id])).rows[0].stored_name;
  const filePath=path.join(storage,`${stored}.bin`);
  const separateProcess=spawnSync(process.execPath,['-e',"const fs=require('fs'),crypto=require('crypto');const hash=crypto.createHash('sha256').update(fs.readFileSync(process.env.QA_FILE)).digest('hex');if(hash!==process.env.QA_HASH)process.exit(1)"],{env:{...process.env,QA_FILE:filePath,QA_HASH:photo.sha256}});
  assert.equal(separateProcess.status,0,'arquivo persiste e mantém hash em outro processo');
  await fs.writeFile(filePath,Buffer.from('alterado'));
  await assert.rejects(() => readVacationDocument(employee,period,leave,photo.id,actor),(error)=>error.status===409);
  await fs.rm(filePath);
  await assert.rejects(() => readVacationDocument(employee,period,leave,photo.id,actor),(error)=>error.status===404);
  const countBefore=(await client.query('SELECT count(*)::int AS total FROM vacation_documents WHERE leave_id=$1',[leave])).rows[0].total;
  await fs.rm(storage,{recursive:true,force:true});
  await fs.writeFile(storage,'bloqueio QA');
  await assert.rejects(() => uploadVacationDocument(employee,period,leave,{documentType:'other',originalName:'novo.pdf',mime:'application/pdf'},pdf,actor));
  assert.equal((await client.query('SELECT count(*)::int AS total FROM vacation_documents WHERE leave_id=$1',[leave])).rows[0].total,countBefore);
  await fs.rm(storage,{force:true});
  console.log('Documentos: upload PDF/PNG, associação, múltiplos anexos, hash, download, ZIP, exclusão lógica, auditoria e saldo preservado: OK');
} finally { await client.end(); await fs.rm(storage,{recursive:true,force:true}); }
